import {chromium, expect} from '@playwright/test'
import {writeFile} from 'node:fs/promises'
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1100}})
const errors=[];page.on('pageerror',error=>errors.push(error.message))
try {
 await page.goto('http://127.0.0.1:4173/#/demo/analysis')
 await expect(page.getByText('Saved to Samby',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Forecasts',exact:true}).click()
 await page.getByRole('button',{name:'New forecast',exact:true}).click()
 await page.getByLabel('Definition name',{exact:true}).fill('Saved observed zero-stock flags')
 const saved=page.waitForResponse(r=>/\/definitions\/[^/]+\/runs$/.test(r.url())&&r.request().method()==='POST')
 await page.getByRole('button',{name:'Save and run',exact:true}).click()
 const submitted=await saved, body=await submitted.json()
 expect(submitted.status(),JSON.stringify(body)).toBe(202)
 await expect(page.getByRole('heading',{name:'Observed zero-stock dates',exact:true})).toBeVisible({timeout:20000})
 const headers=await page.evaluate(()=>{const id=localStorage.getItem('samby.workspace-id.demo');return {'X-Workspace-ID':id,'X-Workspace-Key':localStorage.getItem('samby.workspace-key.'+id)}})
 const response=await page.request.get(`http://127.0.0.1:8001/api/prototype/runs/${body.id}`,{headers})
 const run=await response.json()
 expect(run.status).toBe('succeeded')
 expect(run.result.forecast_diagnostics.stockout_observations.length).toBeGreaterThan(0)
 expect(run.result.history.some(point=>point.observed_zero_stock===1)).toBe(true)
 await page.reload()
 await expect(page.getByRole('heading',{name:'Observed zero-stock dates',exact:true})).toBeVisible()
 await page.getByRole('heading',{name:'Observed zero-stock dates',exact:true}).scrollIntoViewIfNeeded()
 await page.screenshot({path:new URL('stockout-observations.png',import.meta.url).pathname,fullPage:false})
 expect(errors).toEqual([])
 await writeFile(new URL('stockout-observations.json',import.meta.url),JSON.stringify({runId:run.id,stockoutObservations:run.result.forecast_diagnostics.stockout_observations,historyFlags:run.result.history.filter(point=>point.observed_zero_stock===1),reloadPreserved:true,errors},null,2))
 console.log(`Saved forecast ${run.id} retains exact stockout observations and unchanged sold quantities after refresh.`)
} finally {await browser.close()}
