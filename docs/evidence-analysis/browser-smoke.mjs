async function headersFor(id) { return page.evaluate(id => ({'X-Workspace-ID': id, 'X-Workspace-Key': localStorage.getItem('samby.workspace-key.'+id)}),id) }
async function submit() {
  const responsePromise = page.waitForResponse(response => response.url().match(/\/definitions\/[^/]+\/runs$/) && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save and run', exact: true }).click()
  const response = await responsePromise
  const body = await response.json()
  expect(response.status(), JSON.stringify(body)).toBe(202)
  await expect(page).toHaveURL(new RegExp(`run=${body.id}`))
  await expect(page.getByRole('heading', { name: body.definition_name, exact: true })).toBeVisible()
  await expect(page.locator('main .badge').filter({ hasText: /^Completed$/ })).toBeVisible({ timeout: 20000 })
  const result = await page.request.get(`${api}/runs/${body.id}`, { headers })
  const run = await result.json()
  expect(run.status, JSON.stringify(run.error)).toBe('succeeded')
  return run
}
